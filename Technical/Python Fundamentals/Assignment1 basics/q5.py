# 5. If it costs 1600 rs. to fence a rectangular park of length 20 m at the rate of 25 rs. per m², find the breadth of the park and its perimeter. Also, find the area of the field.

cost = 1600
length = 20
rate = 25

perimeter = cost/rate

#perimeter = 2(length + breadth)
breadth = (perimeter/2)-length

area = length * breadth

print(f"Length of park is : {length} m.")
print(f"Breadth of park is : {breadth} m.")
print(f"Perimeter of park is : {perimeter} m.")
print(f"Area of park is : {area} m\u00b2.")
