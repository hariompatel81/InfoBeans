# 25. 100 bricks of length 24 cm and breadth 15 cm are used to tile a path of a garden. What is the area of the path? 

length = 24
breadth = 15

brick_area = length * breadth

path_area = brick_area * 100

print(f"Area of brick is : {brick_area} cm\u00b2.")
print(f"Area of path is : {path_area} cm\u00b2.")