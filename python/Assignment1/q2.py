# 2. The area of a rectangle is 96 cm². If the breadth of the rectangle is 8 cm, find its length and perimeter.

# Area of rectangle is length*breadth
# Area of perimeter is 2(length + width) 

area = 96
breadth = 8
length = area / breadth
perimeter = 2 * (length + breadth)

print(f"Length is : {length} cm.")
print(f"Perimeter is : {perimeter} cm.")
