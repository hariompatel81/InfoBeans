# 1. The perimeter of a rectangle is 230 cm. If the length of the rectangle is 70 cm, find its breadth and area.

#perimeter formula 2(length + breadth)

perimeter = 230
length = 70
breadth = (perimeter / 2) - length
area = length * breadth

print(f"Area is : {area} cm\u00b2 ")
print(f"Breadth is : {breadth} cm.")
