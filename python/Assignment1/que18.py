# 18. Ron jogs around a rectangular park of length 50 m and breadth 30 m. If he takes 10 rounds of the park each day, how much distance does he cover in a day in km? 

# Perimeter of rectengle is 2 (length + breadth)

length = 50
breadth = 30

distance_in_a_day = (10 * (2 * (length + breadth)))/1000

print(f"ron dose cover {distance_in_a_day} km distance in a day.")

